// ── Synthesis helpers ─────────────────────────────────────────────────────────

static uint32_t midi_to_inc(int midi_note)
{
    float freq = 440.0f * powf(2.0f, (midi_note - 69) / 12.0f);
    return (uint32_t)(freq * 16777216.0f / SAMPLE_RATE);
}

static uint32_t inc2_for(int midi_note)
{
    uint32_t base = midi_to_inc(midi_note + osc2_coarse);
    return base + (uint32_t)((uint64_t)base * osc2_fine >> 10);
}

// ── Voice management ──────────────────────────────────────────────────────────

static void voice_start(int v, int midi_note)
{
    v_pitch[v] = midi_note;
    v_gate[v] = true;
    v_phase1[v] = 0;
    v_phase2[v] = 0;
    v_inc1[v] = midi_to_inc(midi_note);
    v_inc2[v] = inc2_for(midi_note);
    v_env[v] = 0;
    v_state[v] = ENV_ATTACK;
}

static void note_on(int midi_note)
{
    // If already playing and sustaining, leave envelope alone
    for (int v = 0; v < MAX_VOICES; v++)
    {
        if (v_gate[v] && v_pitch[v] == midi_note)
        {
            if (v_state[v] == ENV_IDLE || v_state[v] == ENV_RELEASE)
            {
                v_env[v] = 0;
                v_state[v] = ENV_ATTACK;
            }
            return;
        }
    }
    // Use idle voice
    for (int v = 0; v < MAX_VOICES; v++)
    {
        if (v_state[v] == ENV_IDLE)
        {
            voice_start(v, midi_note);
            return;
        }
    }
    // Round-robin steal
    voice_start(voice_rr, midi_note);
    voice_rr = (voice_rr + 1) % MAX_VOICES;
}

static void note_off(int midi_note)
{
    for (int v = 0; v < MAX_VOICES; v++)
    {
        if (v_gate[v] && v_pitch[v] == midi_note)
        {
            v_gate[v] = false;
            if (v_state[v] != ENV_IDLE)
                v_state[v] = ENV_RELEASE;
        }
    }
}

// ── Key press / release ───────────────────────────────────────────────────────

static void key_press(int k)
{
    KeyAssign *a = &key_assign[k];
    if (a->type == KEY_DRUM)
        return; // drums handled separately

    int n = a->n_intervals;
    key_note_n[k] = n;
    for (int i = 0; i < n; i++)
    {
        int note = a->root + a->intervals[i];
        key_notes[k][i] = note;
        note_on(note);
    }
}

static void key_release(int k)
{
    // Build set of notes still held by other keys
    bool still_held[128] = {false};
    for (int j = 0; j < 16; j++)
    {
        if (j == k)
            continue;
        if (!(pressed_keys & (1 << j)))
            continue;
        for (int i = 0; i < key_note_n[j]; i++)
            still_held[key_notes[j][i]] = true;
    }
    for (int i = 0; i < key_note_n[k]; i++)
    {
        int note = key_notes[k][i];
        if (!still_held[note])
            note_off(note);
    }
    key_note_n[k] = 0;
}

// ── Audio fill ────────────────────────────────────────────────────────────────

static void fill_audio_buffer(uint32_t *buf)
{
    // Advance LFO (triangle wave)
    lfo_phase = (lfo_phase + lfo_inc) & 0xFFFFFF;
    int lp = (lfo_phase >> 16) & 255;
    if (lp < 64)
        lfo_val = (int32_t)lp * 512;
    else if (lp < 128)
        lfo_val = (int32_t)(127 - lp) * 512;
    else if (lp < 192)
        lfo_val = -(int32_t)(lp - 128) * 512;
    else
        lfo_val = -(int32_t)(255 - lp) * 512;

    // Advance per-voice ADSR
    for (int v = 0; v < MAX_VOICES; v++)
    {
        switch (v_state[v])
        {
        case ENV_ATTACK:
            v_env[v] += ATTACK_STEP;
            if (v_env[v] >= 32767)
            {
                v_env[v] = 32767;
                v_state[v] = ENV_DECAY;
            }
            break;
        case ENV_DECAY:
            v_env[v] -= DECAY_STEP;
            if (v_env[v] <= SUSTAIN_INT)
            {
                v_env[v] = SUSTAIN_INT;
                v_state[v] = ENV_SUSTAIN;
            }
            break;
        case ENV_RELEASE:
            v_env[v] -= RELEASE_STEP;
            if (v_env[v] <= 0)
            {
                v_env[v] = 0;
                v_state[v] = ENV_IDLE;
            }
            break;
        default:
            break;
        }
    }

    // Check if anything to render
    bool any_voice = false;
    for (int v = 0; v < MAX_VOICES; v++)
        if (v_state[v] != ENV_IDLE)
        {
            any_voice = true;
            break;
        }
    bool has_drum = (active_drum != NULL);

    if (!any_voice && !has_drum)
    {
        memset(buf, 0, BUFFER_SIZE * sizeof(uint32_t));
        return;
    }

    // Pre-compute LFO-modulated increments
    uint32_t im1[MAX_VOICES], im2[MAX_VOICES];
    for (int v = 0; v < MAX_VOICES; v++)
    {
        if (v_state[v] != ENV_IDLE && lfo_depth > 0)
        {
            int64_t mod1 = ((int64_t)v_inc1[v] * lfo_val >> 20) * lfo_depth >> 6;
            int64_t mod2 = ((int64_t)v_inc2[v] * lfo_val >> 20) * lfo_depth >> 6;
            im1[v] = (uint32_t)((int64_t)v_inc1[v] + mod1);
            im2[v] = (uint32_t)((int64_t)v_inc2[v] + mod2);
        }
        else
        {
            im1[v] = v_inc1[v];
            im2[v] = v_inc2[v];
        }
    }

    for (int i = 0; i < BUFFER_SIZE; i++)
    {
        int32_t cs = 0;

        for (int v = 0; v < MAX_VOICES; v++)
        {
            if (v_state[v] == ENV_IDLE)
                continue;
            int32_t ea = v_env[v];

            // OSC1
            int pb1 = (int)((v_phase1[v] >> 16) & 255);
            int32_t s1;
            switch (current_waveform)
            {
            case 0:
                s1 = sine_table[pb1];
                break;
            case 1:
                s1 = pb1 < 128 ? 32767 : -32767;
                break;
            case 2:
                s1 = pb1 < 128 ? (pb1 * 516 - 32767) : ((255 - pb1) * 516 - 32767);
                break;
            default:
                s1 = pb1 * 256 - 32768;
                break;
            }
            v_phase1[v] += im1[v]; // Use full 32-bit precision (natural wraparound)

            // OSC2
            int pb2 = (int)((v_phase2[v] >> 16) & 255);
            int32_t s2;
            switch (current_waveform)
            {
            case 0:
                s2 = sine_table[pb2];
                break;
            case 1:
                s2 = pb2 < 128 ? 32767 : -32767;
                break;
            case 2:
                // Triangle: proper ramp up/down with correct scaling
                s2 = pb2 < 128 ? ((pb2 << 9) - 32767) : ((32767 - (pb2 - 128) * 512));
                break;
            default:
                // Sawtooth: -32768 to +32767
                s2 = (pb2 << 8) - 32768;
                break;
            }
            v_phase2[v] += im2[v]; // Use full 32-bit precision (natural wraparound)

            // Mix + envelope: >>23 = /64 (mix) /32767 (env norm) /4 (voice headroom)
            cs += (int32_t)(((int64_t)(s1 * osc1_mix + s2 * osc2_mix) * ea) >> 23);
        }

        // Drum (scale to 95% for good presence without excessive clipping)
        int32_t ds = 0;
        if (has_drum)
        {
            ds = (active_drum[drum_pos++] * 498072) >> 16; // 8x scaling
            if (drum_pos >= active_drum_len)
            {
                active_drum = NULL;
                has_drum = false;
            }
        }

        int32_t s = cs + ds;

        // Apply master gain from volume pot. Above 100% is allowed via
        // master_gain_q8 and shaped by the soft limiter below.
        s = (int32_t)(((int64_t)s * master_gain_q8) >> 8);

        // Soft-knee limiter: gently compress above ~73% FS to reduce harsh clip.
        int32_t a = s >= 0 ? s : -s;
        if (a > 24000)
        {
            int32_t excess = a - 24000;
            a = 24000 + (excess >> 2); // 4:1 compression above knee
            if (a > 32767)
                a = 32767;
            s = s >= 0 ? a : -a;
        }

        if (s > 32767)
            s = 32767;
        if (s < -32768)
            s = -32768;

        // Pack as 32-bit word: left in high 16, right in low 16
        uint16_t u = (uint16_t)(int16_t)s;
        buf[i] = ((uint32_t)u << 16) | u;
    }
}

// ── DMA interrupt ─────────────────────────────────────────────────────────────

static void dma_irq_handler(void)
{
    dma_hw->ints0 = 1u << dma_chan;

    // Restart DMA on the just-finished buffer index (now "next to fill")
    int fill_buf = dma_play_idx;
    dma_play_idx ^= 1;

    // Point DMA at the other buffer (the one we just swapped to)
    dma_channel_set_read_addr(dma_chan, audio_buf[dma_play_idx], true);

    // Signal main loop to fill fill_buf
    // We use a simple flag; fill_audio_buffer() is called from main()
    (void)fill_buf; // main reads dma_play_idx ^ 1 to know which to fill
    need_fill = true;
}

// ── I2S / DMA setup ───────────────────────────────────────────────────────────

static void i2s_dma_init(void)
{
    audio_pio = pio0;
    uint offset = pio_add_program(audio_pio, &i2s_out_program);
    audio_sm = pio_claim_unused_sm(audio_pio, true);

    i2s_out_program_init(audio_pio, audio_sm, offset,
                         PIN_I2S_DATA, PIN_I2S_BCLK, SAMPLE_RATE);

    // Zero out both buffers
    memset(audio_buf, 0, sizeof(audio_buf));

    dma_chan = dma_claim_unused_channel(true);
    dma_channel_config cfg = dma_channel_get_default_config(dma_chan);
    channel_config_set_transfer_data_size(&cfg, DMA_SIZE_32);
    channel_config_set_read_increment(&cfg, true);
    channel_config_set_write_increment(&cfg, false);
    channel_config_set_dreq(&cfg, pio_get_dreq(audio_pio, audio_sm, true));

    dma_channel_configure(dma_chan, &cfg,
                          &audio_pio->txf[audio_sm], // write to PIO TX FIFO
                          audio_buf[0],              // read from buffer 0
                          BUFFER_SIZE,
                          false);

    dma_channel_set_irq0_enabled(dma_chan, true);
    irq_set_exclusive_handler(DMA_IRQ_0, dma_irq_handler);
    irq_set_enabled(DMA_IRQ_0, true);

    dma_play_idx = 0;
    dma_channel_start(dma_chan);
}

// ── TLV320DAC3100 init ────────────────────────────────────────────────────────

static void tlv_write(uint8_t reg, uint8_t val)
{
    uint8_t buf[2] = {reg, val};
    i2c_write_blocking(I2C_BUS, TLV_ADDR, buf, 2, false);
}

static void tlv_init(void)
{
    // Page 0
    tlv_write(0x00, 0x00); // select page 0
    tlv_write(0x01, 0x01); // software reset
    sleep_ms(10);

    // I2S slave mode, 16-bit word length
    // Reg 27: bit7=BCLK_OUT=0(input), bit6=WS_OUT=0(input), bits5:4=00(I2S), bits1:0=00(16-bit)
    tlv_write(0x1B, 0x00);

    // Power up DAC: left + right powered, softstepping enabled
    tlv_write(0x3F, 0xD4); // reg 63: power up L+R DAC, soft-step 1/fs
    tlv_write(0x40, 0x00); // reg 64: left data→left DAC, right data→right DAC
    tlv_write(0x41, 0x00); // reg 65: left DAC digital volume = 0 dB
    tlv_write(0x42, 0x00); // reg 66: right DAC digital volume = 0 dB

    // Page 1: output driver config
    tlv_write(0x00, 0x01); // select page 1
    tlv_write(0x01, 0x08); // reg 1: AVDD/DVDD scheme
    sleep_ms(10);
    tlv_write(0x09, 0x3C); // reg 9:  power up HPL driver
    tlv_write(0x0A, 0x3C); // reg 10: power up HPR driver
    tlv_write(0x0C, 0x08); // reg 12: route DAC_L to HPL
    tlv_write(0x0D, 0x08); // reg 13: route DAC_R to HPR

    tlv_write(0x00, 0x00); // back to page 0
    printf("TLV320DAC3100 ready\n");
}

// ── Pimoroni RGB Keypad LEDs (APA102 / DotStar) ───────────────────────────────
// 16 LEDs — send start frame, 16 LED frames, end frame

static uint8_t led_r[16], led_g[16], led_b[16];
// APA102 global brightness: 1..31 (lower = dimmer). 8 is a good low-power default.
static const uint8_t LED_GLOBAL_BRIGHTNESS = 1;

static void apa102_send_byte(uint8_t byte)
{
    spi_write_blocking(SPI_KEYPAD, &byte, 1);
}

static void update_leds(void)
{
    // Pimoroni keypad latches LED data with CS framing.
    gpio_put(PIN_APA_CS, 0);
    // Start frame
    for (int i = 0; i < 4; i++)
        apa102_send_byte(0x00);
    // LED frames: 0b111xxxxx brightness header, then B, G, R
    for (int i = 0; i < 16; i++)
    {
        apa102_send_byte((uint8_t)(0xE0 | (LED_GLOBAL_BRIGHTNESS & 0x1F)));
        apa102_send_byte(led_b[i]);
        apa102_send_byte(led_g[i]);
        apa102_send_byte(led_r[i]);
    }
    // End frame (need N/2 clocks for 16 LEDs → 1 byte min, send 4)
    for (int i = 0; i < 4; i++)
        apa102_send_byte(0xFF);
    gpio_put(PIN_APA_CS, 1);
}

static void set_led(int k, uint8_t r, uint8_t g, uint8_t b)
{
    led_r[k] = r;
    led_g[k] = g;
    led_b[k] = b;
}

// Chord type → LED color
static void chord_color(const int *ivs, int n, uint8_t *r, uint8_t *g, uint8_t *b)
{
    int i1 = n > 1 ? ivs[1] : -1;
    int i2 = n > 2 ? ivs[2] : -1;
    int i3 = n > 3 ? ivs[3] : -1;
    if (i1 == 4 && i2 == 7 && i3 == -1)
    {
        *r = 0;
        *g = 32;
        *b = 0;
        return;
    } // Major  green
    if (i1 == 3 && i2 == 7 && i3 == -1)
    {
        *r = 0;
        *g = 0;
        *b = 32;
        return;
    } // Minor  blue
    if (i1 == 3 && i2 == 6)
    {
        *r = 20;
        *g = 0;
        *b = 32;
        return;
    } // Dim    purple
    if (i1 == 4 && i2 == 8)
    {
        *r = 32;
        *g = 12;
        *b = 0;
        return;
    } // Aug    orange
    if (i1 == 2 && i2 == 7)
    {
        *r = 0;
        *g = 28;
        *b = 32;
        return;
    } // Sus2   cyan
    if (i1 == 5 && i2 == 7)
    {
        *r = 0;
        *g = 28;
        *b = 32;
        return;
    } // Sus4   cyan
    if (i3 == 11)
    {
        *r = 32;
        *g = 28;
        *b = 0;
        return;
    } // Maj7   yellow
    if (i3 == 10)
    {
        *r = 32;
        *g = 28;
        *b = 0;
        return;
    } // Dom7   yellow
    *r = 16;
    *g = 16;
    *b = 16;
}

static void refresh_leds(void)
{
    for (int k = 0; k < 16; k++)
    {
        if (pressed_keys & (1 << k))
        {
            set_led(k, 64, 64, 64); // bright white = held
        }
        else
        {
            KeyAssign *a = &key_assign[k];
            if (a->type == KEY_DRUM)
            {
                set_led(k, 22, 22, 22);
            }
            else
            {
                uint8_t r, g, b;
                chord_color(a->intervals, a->n_intervals, &r, &g, &b);
                set_led(k, r, g, b);
            }
        }
    }
    update_leds();
}

