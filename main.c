static void oled_cmd(uint8_t c)
{
    uint8_t buf[2] = {0x00, c};
    i2c_write_blocking(I2C_BUS, oled_addr, buf, 2, false);
}

static bool i2c_addr_present(uint8_t addr)
{
    uint8_t dummy;
    return i2c_read_blocking(I2C_BUS, addr, &dummy, 1, false) >= 0;
}

static void oled_init(void)
{
    if (i2c_addr_present(0x3C))
        oled_addr = 0x3C;
    else if (i2c_addr_present(0x3D))
        oled_addr = 0x3D;
    else
    {
        printf("OLED not found at 0x3C/0x3D\n");
        return;
    }

    sleep_ms(100);  // give OLED power rail time to stabilize
    oled_cmd(0xAE); // display off
    oled_cmd(0xD5);
    oled_cmd(0x80); // clock divide ratio / osc freq
    oled_cmd(0xA8);
    oled_cmd(0x3F); // multiplex ratio = 64
    oled_cmd(0xD3);
    oled_cmd(0x00); // display offset = 0
    oled_cmd(0x40); // display start line = 0
    oled_cmd(0xAD);
    oled_cmd(0x8B); // charge pump: internal VCC  ← SH1106 specific
    oled_cmd(0x32); // charge pump voltage: 9V             ← SH1106 specific
    oled_cmd(0xA1); // segment re-map: col 131 → SEG0 (mirror)
    oled_cmd(0xC8); // COM scan direction: remapped
    oled_cmd(0xDA);
    oled_cmd(0x12); // COM pins hardware config
    oled_cmd(0x81);
    oled_cmd(0xCF); // contrast
    oled_cmd(0xD9);
    oled_cmd(0x1F); // pre-charge period  ← was 0xF1, wrong for internal pump
    oled_cmd(0xDB);
    oled_cmd(0x40); // VCOM deselect level
    oled_cmd(0xA4); // output follows RAM (not all-on)
    oled_cmd(0xA6); // normal display (not inverted)
    sleep_ms(10);
    oled_cmd(0xAF); // display ON
    sleep_ms(10);
    memset(oled_buf, 0, sizeof(oled_buf));
    oled_flush(); // push blank frame before printing ready
    printf("OLED ready at 0x%02X\n", oled_addr);
}

// Set a single pixel in the framebuffer
static void oled_pixel(int x, int y, bool on)
{
    if ((unsigned)x >= OLED_W || (unsigned)y >= OLED_H)
        return;
    int page = y >> 3;
    int bit = y & 7;
    if (on)
        oled_buf[page * OLED_W + x] |= (uint8_t)(1 << bit);
    else
        oled_buf[page * OLED_W + x] &= ~(uint8_t)(1 << bit);
}

// Draw a character at pixel position (x, y). Returns new x.
static int oled_char(int x, int y, char c)
{
    if (c < ' ' || c > 'Z')
        c = ' ';
    const uint8_t *g = font5x7[(uint8_t)(c - ' ')];
    for (int col = 0; col < 5; col++)
    {
        uint8_t bits = g[col];
        for (int row = 0; row < 7; row++)
        {
            if (bits & (1 << row))
                oled_pixel(x + col, y + row, true);
        }
    }
    return x + 6; // 5px glyph + 1px gap
}

static void oled_str(int x, int y, const char *s)
{
    while (*s)
        x = oled_char(x, y, *s++);
}

// Push framebuffer to display (SH1106 page-addressed, 2-col offset)
static void oled_flush(void)
{
    uint8_t row_buf[129];
    row_buf[0] = 0x40; // Co=0, D/C#=1 → data stream
    for (int pg = 0; pg < OLED_PAGES; pg++)
    {
        oled_cmd(0xB0 + pg); // set page address
        oled_cmd(0x02);      // column low  nibble = 2 (SH1106 2-col offset, low  nibble)
        oled_cmd(0x10);      // column high nibble = 0 (high nibble command = 0x10 + 0)
        memcpy(row_buf + 1, oled_buf + pg * OLED_W, OLED_W);
        i2c_write_blocking(I2C_BUS, oled_addr, row_buf, 129, false);
    }
}

// Generate a 4-char label string for key k
static void key_label(int k, char out[5])
{
    static const char *drum_names[8] = {
        "KICK", "SNAR", "HHAT", "CLAP", "TOM1", "TOM2", "TOM3", "CYMB"};
    static const char *note_names[12] = {
        "C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"};
    KeyAssign *a = &key_assign[k];
    if (a->type == KEY_DRUM)
    {
        memcpy(out, drum_names[a->root % 8], 4);
        out[4] = '\0';
        return;
    }
    // Chord: root note + type abbreviation
    const char *note = note_names[a->root % 12];
    const char *ctype = "??? ";
    if (a->n_intervals == 3 && a->intervals[1] == 4 && a->intervals[2] == 7)
        ctype = "MAJ";
    else if (a->n_intervals == 3 && a->intervals[1] == 3 && a->intervals[2] == 7)
        ctype = "MIN";
    else if (a->n_intervals == 3 && a->intervals[1] == 3 && a->intervals[2] == 6)
        ctype = "DIM";
    else if (a->n_intervals == 3 && a->intervals[1] == 4 && a->intervals[2] == 8)
        ctype = "AUG";
    else if (a->n_intervals == 3 && a->intervals[1] == 2 && a->intervals[2] == 7)
        ctype = "SS2";
    else if (a->n_intervals == 3 && a->intervals[1] == 5 && a->intervals[2] == 7)
        ctype = "SS4";
    else if (a->n_intervals == 4 && a->intervals[3] == 10)
        ctype = "DM7";
    else if (a->n_intervals == 4 && a->intervals[3] == 11 && a->intervals[1] == 4)
        ctype = "MM7";
    else if (a->n_intervals == 4 && a->intervals[3] == 10 && a->intervals[1] == 3)
        ctype = "MN7";
    snprintf(out, 5, "%s%s", note, ctype);
}

// Draw the 4×4 key grid into oled_buf
static void draw_grid(void)
{
    memset(oled_buf, 0, sizeof(oled_buf));
    // Grid lines
    for (int y = 0; y < OLED_H; y++)
    {
        oled_pixel(0, y, true);
        oled_pixel(31, y, true);
        oled_pixel(63, y, true);
        oled_pixel(95, y, true);
        oled_pixel(127, y, true);
    }
    for (int x = 0; x < OLED_W; x++)
    {
        oled_pixel(x, 0, true);
        oled_pixel(x, 15, true);
        oled_pixel(x, 31, true);
        oled_pixel(x, 47, true);
        oled_pixel(x, 63, true);
    }
    // Labels and press highlights
    char label[5];
    for (int row = 0; row < 4; row++)
    {
        for (int col = 0; col < 4; col++)
        {
            int k = row * 4 + col;
            int cx = col * 32; // cell left edge (= border pixel)
            int cy = row * 16; // cell top edge  (= border pixel)
            // Invert cell background if key is held
            if (pressed_keys & (1 << k))
            {
                for (int px = cx + 1; px < cx + 31; px++)
                    for (int py = cy + 1; py < cy + 15; py++)
                        oled_pixel(px, py, true);
            }
            key_label(k, label);
            // Clip label to 4 chars, uppercase only
            for (int i = 0; i < 4 && label[i]; i++)
                if (label[i] >= 'a' && label[i] <= 'z')
                    label[i] -= 32;
            label[4] = '\0';
            int lw = (int)strlen(label) * 6 - 1;
            int tx = cx + 1 + (30 - lw) / 2; // centered in 30px inner width
            int ty = cy + 4;                 // 4px from top (7px font in 14px)
            // If inverted, draw in "off" pixels so text is dark on bright bg
            if (pressed_keys & (1 << k))
            {
                for (int c2 = 0; label[c2]; c2++)
                {
                    if (label[c2] < ' ' || label[c2] > 'Z')
                    {
                        tx += 6;
                        continue;
                    }
                    const uint8_t *g = font5x7[(uint8_t)(label[c2] - ' ')];
                    for (int fc = 0; fc < 5; fc++)
                        for (int fr = 0; fr < 7; fr++)
                            if (g[fc] & (1 << fr))
                                oled_pixel(tx + fc, ty + fr, false);
                    tx += 6;
                }
            }
            else
            {
                oled_str(tx, ty, label);
            }
        }
    }
}

