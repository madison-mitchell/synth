// ── TCA9555 button reading ────────────────────────────────────────────────────
// Pimoroni RGB Keypad uses TCA9555 (not MCP23017). Register map:
//   0x00 / 0x01 = Input Port 0/1  (read buttons here)
//   0x06 / 0x07 = Config Port 0/1 (1=input, default 0xFF — all inputs)

static void mcp_write(uint8_t reg, uint8_t val)
{
    uint8_t buf[2] = {reg, val};
    i2c_write_blocking(I2C_BUS, MCP_ADDR, buf, 2, false);
}

static uint8_t mcp_read(uint8_t reg)
{
    i2c_write_blocking(I2C_BUS, MCP_ADDR, &reg, 1, true);
    uint8_t val;
    i2c_read_blocking(I2C_BUS, MCP_ADDR, &val, 1, false);
    return val;
}

static void mcp_init(void)
{
    // TCA9555 defaults to all-input mode; write config regs explicitly anyway
    mcp_write(0x06, 0xFF); // Config Port 0: all inputs
    mcp_write(0x07, 0xFF); // Config Port 1: all inputs
    printf("TCA9555 ready\n");
}

// Returns 16-bit bitmask of raw button states (1 = pressed, active low inverted)
static uint16_t mcp_read_buttons(void)
{
    uint8_t a = ~mcp_read(0x00); // Input Port 0, invert (pressed=low → 1)
    uint8_t b = ~mcp_read(0x01); // Input Port 1
    return (uint16_t)a | ((uint16_t)b << 8);
}

