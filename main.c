int main(void)
{
    stdio_init_all();
    sleep_ms(2000);
    // If USB serial is connected, allow a brief pause for interactive boot.
    // Continue automatically so the synth still starts when running standalone.
    printf("Press any key to boot (auto-continue in 2s)...\n");
    int ch = getchar_timeout_us(2000000);
    if (ch == PICO_ERROR_TIMEOUT)
        printf("No serial input detected, continuing boot.\n");
    printf("=== PICO SYNTH v1.0 (C) ===\n");

    // ── Sine table ────────────────────────────────────────────────────────
    for (int i = 0; i < 256; i++)
        sine_table[i] = (int16_t)(sinf(2.0f * (float)M_PI * i / 256.0f) * 32767.0f);

    // ── Drum tables ───────────────────────────────────────────────────────
    printf("Drum samples compiled in from audio files\n");
    printf("Drums ready\n");

    // ── Voice init ────────────────────────────────────────────────────────
    memset(v_state, ENV_IDLE, sizeof(v_state));
    memset(v_gate, 0, sizeof(v_gate));

    // ── I2C init (keypad + TLV320) ────────────────────────────────────────
    // 400 kHz (fast mode) for lower latency — button/LED polling can saturate bus
    i2c_init(I2C_BUS, 400 * 1000);
    gpio_set_function(PIN_I2C_SDA, GPIO_FUNC_I2C);
    gpio_set_function(PIN_I2C_SCL, GPIO_FUNC_I2C);
    gpio_pull_up(PIN_I2C_SDA);
    gpio_pull_up(PIN_I2C_SCL);

    // ── TLV320 DAC init ───────────────────────────────────────────────────
    tlv_init();

    // ── I2S + DMA ─────────────────────────────────────────────────────────
    i2s_dma_init();
    printf("I2S DMA ready\n");

    // ── Keypad LEDs (APA102 via SPI0, Pimoroni pinout) ───────────────────
    spi_init(SPI_KEYPAD, 4 * 1000 * 1000);
    gpio_set_function(PIN_APA_SCK, GPIO_FUNC_SPI);
    gpio_set_function(PIN_APA_MOSI, GPIO_FUNC_SPI);
    gpio_init(PIN_APA_CS);
    gpio_set_dir(PIN_APA_CS, GPIO_OUT);
    gpio_put(PIN_APA_CS, 1);

    // ── Keypad buttons (TCA9555 via I2C0) ────────────────────────────────
    mcp_init();

    // ── OLED display (SH1106 via I2C0 — wire SDA→GP4, SCL→GP5) ──────────
    oled_init();

    // ── I2C bus scan (after init so all devices are settled) ─────────────
    printf("I2C scan (SDA=GP%d SCL=GP%d):\n", PIN_I2C_SDA, PIN_I2C_SCL);
    for (int addr = 0x08; addr < 0x78; addr++)
    {
        uint8_t rxdata;
        int ret = i2c_read_blocking(I2C_BUS, addr, &rxdata, 1, false);
        if (ret >= 0)
        {
            printf("  found 0x%02X\n", addr);
            if (addr == MCP_ADDR)
                dev_found_tca = true;
            if (addr == TLV_ADDR)
                dev_found_tlv = true;
            if (addr == 0x3C || addr == 0x3D)
                dev_found_oled = true;
        }
    }
    printf("I2C scan done  TCA=%d TLV=%d OLED=%d\n",
           dev_found_tca, dev_found_tlv, dev_found_oled);

    // ── ADC ───────────────────────────────────────────────────────────────
    adc_init();
    adc_gpio_init(26); // ADC0 = GP26 (volume)
    adc_gpio_init(27); // ADC1 = GP27 (vib rate)
    adc_gpio_init(28); // ADC2 = GP28 (vib depth)

    // ── Encoder ───────────────────────────────────────────────────────────
    gpio_init(PIN_ENC_CLK);
    gpio_set_dir(PIN_ENC_CLK, GPIO_IN);
    gpio_pull_up(PIN_ENC_CLK);
    gpio_init(PIN_ENC_DT);
    gpio_set_dir(PIN_ENC_DT, GPIO_IN);
    gpio_pull_up(PIN_ENC_DT);
    gpio_init(PIN_ENC_SW);
    gpio_set_dir(PIN_ENC_SW, GPIO_IN);
    gpio_pull_up(PIN_ENC_SW);
    enc_last_clk = gpio_get(PIN_ENC_CLK);
    enc_last_sw = gpio_get(PIN_ENC_SW);

    // ── Default key layout ────────────────────────────────────────────────
    setup_default_layout();

    // ── Initial LED draw ──────────────────────────────────────────────────
    led_self_test();
    refresh_leds();

    printf("=== READY — press a key! ===\n");

    // ── Main loop ─────────────────────────────────────────────────────────
    uint32_t last_ui_ms = to_ms_since_boot(get_absolute_time());
    uint32_t last_dbg_ms = 0;  // debug print every 1 s
    uint32_t last_disp_ms = 0; // OLED redraw throttle
    uint16_t last_drawn_keys = 0xFFFF;

    while (true)
    {
        // Fill audio if DMA interrupt requested it
        if (need_fill)
        {
            need_fill = false;
            int fill_buf = dma_play_idx ^ 1; // the buffer NOT currently playing
            fill_audio_buffer(audio_buf[fill_buf]);
        }

        // Throttle UI to ~333 Hz (3ms) for responsive button input
        uint32_t now = to_ms_since_boot(get_absolute_time());
        if (now - last_ui_ms < 3)
            continue;
        last_ui_ms = now;

        // ── Encoder ──────────────────────────────────────────────────
        bool enc_pressed;
        int rot = read_encoder(&enc_pressed);
        if (rot != 0)
        {
            current_waveform = (current_waveform + rot + 4) & 3;
            printf("Waveform: %d\n", current_waveform);
        }
        (void)enc_pressed; // GUI navigation not implemented yet

        // ── Pots ─────────────────────────────────────────────────────
        int vol_unused, vib_rate, vib_depth;
        read_pots(&vol_unused, &vib_rate, &vib_depth);
        // No volume pot connected: keep fixed at 2.55x (653 in Q8 format, 85% of previous 3.0x).
        master_gain_q8 = 653;
        lfo_inc = (uint32_t)((float)vib_rate * 16777216.0f / SAMPLE_RATE);
        lfo_depth = vib_depth;

        // ── Button scan (debounced press + release) ───────────────────
        uint16_t raw = mcp_read_buttons();

        // Debug: print raw button bits and encoder state once per second
        if (now - last_dbg_ms >= 1000)
        {
            last_dbg_ms = now;
            printf("BTN raw=0x%04X  ENC clk=%d dt=%d sw=%d  [TCA=%d TLV=%d OLED=%d@0x%02X]\n",
                   raw,
                   gpio_get(PIN_ENC_CLK),
                   gpio_get(PIN_ENC_DT),
                   gpio_get(PIN_ENC_SW),
                   dev_found_tca, dev_found_tlv, dev_found_oled, oled_addr);
        }

        for (int k = 0; k < 16; k++)
        {
            bool in_raw = (raw >> k) & 1;
            bool in_pressed = (pressed_keys >> k) & 1;

            if (in_raw)
            {
                press_count[k]++;
                release_count[k] = 0;
            }
            else
            {
                if (in_pressed)
                    release_count[k]++;
                press_count[k] = 0;
            }
        }

        uint16_t new_pressed = 0;
        for (int k = 0; k < 16; k++)
        {
            bool in_pressed = (pressed_keys >> k) & 1;
            if (press_count[k] >= PRESS_SCANS)
                new_pressed |= (1 << k);
            else if (in_pressed && release_count[k] < RELEASE_SCANS)
                new_pressed |= (1 << k); // within release debounce window
        }

        // ── React to changes ──────────────────────────────────────────
        if (new_pressed != pressed_keys)
        {
            uint16_t just_pressed = new_pressed & ~pressed_keys;
            uint16_t just_released = pressed_keys & ~new_pressed;
            pressed_keys = new_pressed;

            for (int k = 0; k < 16; k++)
            {
                if (just_released & (1 << k))
                {
                    if (key_assign[k].type == KEY_CHORD)
                        key_release(k);
                }
            }
            for (int k = 0; k < 16; k++)
            {
                if (just_pressed & (1 << k))
                {
                    KeyAssign *a = &key_assign[k];
                    if (a->type == KEY_DRUM)
                    {
                        // a->root is 0-3, maps to drum_samples array
                        if (a->root >= 0 && a->root < 4)
                        {
                            active_drum = drum_samples[a->root].data;
                            active_drum_len = drum_samples[a->root].len;
                        }
                        drum_pos = 0;
                    }
                    else
                    {
                        key_press(k);
                    }
                }
            }
            refresh_leds();
        }

        // ── OLED refresh (event-driven + slow keepalive) ──────────────
        // Full-screen I2C flushes are expensive; redraw on key changes.
        if (dev_found_oled && (pressed_keys != last_drawn_keys || now - last_disp_ms >= 500))
        {
            last_disp_ms = now;
            last_drawn_keys = pressed_keys;
            draw_grid();
            oled_flush();
        }
    }
}
