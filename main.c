// ── ADC pot reading ───────────────────────────────────────────────────────────

// Returns 0..100 for volume, 2..8 for vib_rate, 0..50 for vib_depth
static void read_pots(int *vol, int *vib_rate, int *vib_depth)
{
    adc_select_input(POT_CH_VOL);
    int v = (int)(adc_read() * 100 / 4095);
    *vol = v < 0 ? 0 : (v > 100 ? 100 : v);

    adc_select_input(POT_CH_RATE);
    v = 2 + (int)(adc_read() * 6 / 4095);
    *vib_rate = v < 2 ? 2 : (v > 8 ? 8 : v);

    adc_select_input(POT_CH_DEPTH);
    v = (int)(adc_read() * 50 / 4095);
    *vib_depth = v < 0 ? 0 : (v > 50 ? 50 : v);
}

// ── Encoder reading ───────────────────────────────────────────────────────────

// Returns -1, 0, or +1 for rotation; sets *pressed if button newly pressed
static int read_encoder(bool *pressed)
{
    int clk = gpio_get(PIN_ENC_CLK);
    int rot = 0;
    if (clk != enc_last_clk)
    {
        if (clk == 0)
            rot = gpio_get(PIN_ENC_DT) ? 1 : -1;
        enc_last_clk = clk;
    }

    bool sw = gpio_get(PIN_ENC_SW);
    *pressed = false;
    if (!sw && enc_last_sw)
    {
        uint32_t now = to_ms_since_boot(get_absolute_time());
        if (now - last_enc_ms > 300)
        {
            *pressed = true;
            last_enc_ms = now;
        }
    }
    enc_last_sw = sw;
    return rot;
}

